#!/usr/bin/env node
// Cross-check vectors for crates/humid-pq2 made with the JavaScript the 4.x app ships (the
// pinned @noble/post-quantum, @noble/curves, @noble/hashes and @noble/ciphers), written to
// crates/humid-pq2/tests/vectors/noble-interop.json. The Rust KATs (crates/humid-pq2/src/kat.rs)
// check that the Rust suite gives the same bytes:
//
//   * ML-KEM-1024: keygen from (d, z), encapsulation with a given m, decapsulation;
//   * ML-DSA-87: keygen from ξ; hedged signatures with a given rnd and a HUMID-PQ2 context,
//     so the randomness path (not only the deterministic one) is compared;
//   * X25519 and SLH-DSA-SHA2-256s keygen;
//   * HUMID-PQ2 itself, computed here independently from docs/v5/PQ2.md: the KMAC256 KDF,
//     the hybrid KEM combiner, the labelled hash, an at-rest box and a sealed box.
//
// Inputs are derived from a fixed seed (SHAKE256), so the file is reproducible:
//   node tools/pq2-noble-vectors.mjs   (then `cargo test` in crates/humid-pq2)
import { writeFileSync } from "node:fs";
import { ml_kem1024 } from "@noble/post-quantum/ml-kem.js";
import { ml_dsa87 } from "@noble/post-quantum/ml-dsa.js";
import { slh_dsa_sha2_256s } from "@noble/post-quantum/slh-dsa.js";
import { x25519 } from "@noble/curves/ed25519.js";
import { shake256, sha3_512 } from "@noble/hashes/sha3.js";
import { kmac256 } from "@noble/hashes/sha3-addons.js";
import { gcmsiv } from "@noble/ciphers/aes.js";

const out = new URL("../crates/humid-pq2/tests/vectors/noble-interop.json", import.meta.url);
const hex = (b) => Buffer.from(b).toString("hex");
const utf8 = (s) => new TextEncoder().encode(s);
const cat = (...a) => { const r = new Uint8Array(a.reduce((n, x) => n + x.length, 0)); let o = 0; for (const x of a) { r.set(x, o); o += x.length; } return r; };
const u16 = (n) => new Uint8Array([n >> 8, n & 255]);
const u32 = (n) => { const b = new Uint8Array(4); new DataView(b.buffer).setUint32(0, n); return b; };
const lp = (...parts) => cat(...parts.flatMap((p) => [u32(p.length), p]));
let counter = 0;
const det = (n) => shake256(cat(utf8("humid-pq2 noble interop"), u32(counter++)), { dkLen: n });

// HUMID-PQ2 (docs/v5/PQ2.md), independently of the Rust code.
const SUITE = cat(utf8("HUMID-PQ2"), u16(1));
const header = (type) => cat(SUITE, u16(type));
const kdf = (label, key, ctx, len) => kmac256(lp(...key), cat(SUITE, lp(...ctx)), { personalization: utf8(label), dkLen: len });
const labelledHash = (label, parts) => sha3_512(cat(SUITE, lp(utf8(label), ...parts)));
const keyId = (enc) => labelledHash("HUMID-PQ2 key-id", [enc]).subarray(0, 32);
const T = { KEM_PK: 0x0001, KEM_CT: 0x0002, AT_REST: 0x0009, SEALED: 0x000a };

const doc = { note: "Generated by tools/pq2-noble-vectors.mjs with @noble/post-quantum 0.7.1, @noble/curves/hashes/ciphers 2.4.0. Do not edit.", mlkem: [], mldsa: [], x25519: [], slh: [], pq2: {} };

for (let i = 0; i < 4; i++) {
  const d = det(32), z = det(32), m = det(32);
  const k = ml_kem1024.keygen(cat(d, z));
  const e = ml_kem1024.encapsulate(k.publicKey, m);
  const bad = det(1568);
  doc.mlkem.push({ d: hex(d), z: hex(z), m: hex(m), ek: hex(k.publicKey), dkSha3: hex(sha3_512(k.secretKey)), ct: hex(e.cipherText), ss: hex(e.sharedSecret), badCt: hex(bad), badSs: hex(ml_kem1024.decapsulate(bad, k.secretKey)) });
}

for (let i = 0; i < 3; i++) {
  const xi = det(32), msg = det(17 + 50 * i), rnd = det(32);
  const ctx = cat(SUITE, u16(0x0004), utf8("HUMID-PQ2 interop"));
  const k = ml_dsa87.keygen(xi);
  const hedged = ml_dsa87.sign(msg, k.secretKey, { context: ctx, extraEntropy: rnd });
  const detSig = ml_dsa87.sign(msg, k.secretKey, { context: ctx, extraEntropy: false });
  doc.mldsa.push({ xi: hex(xi), pk: hex(k.publicKey), msg: hex(msg), ctx: hex(ctx), rnd: hex(rnd), sigHedged: hex(hedged), sigDeterministic: hex(detSig) });
}

for (let i = 0; i < 3; i++) {
  const a = det(32), b = det(32);
  doc.x25519.push({ a: hex(a), b: hex(b), pubA: hex(x25519.getPublicKey(a)), shared: hex(x25519.getSharedSecret(a, x25519.getPublicKey(b))) });
}

{
  const seed = det(96);
  const k = slh_dsa_sha2_256s.keygen(seed);
  doc.slh.push({ seed: hex(seed), pk: hex(k.publicKey) });
}

// --- HUMID-PQ2 objects ---
{
  // KDF
  const kdfCases = [];
  for (const [label, key, ctx, len] of [
    ["HUMID-PQ2 doc", [det(32), det(32), det(32)], [utf8("doc-1"), det(64)], 32],
    ["HUMID-PQ2 device-wrap", [det(32)], [utf8("dev_1"), new Uint8Array(8)], 32],
    ["HUMID-PQ2 test", [], [], 100],
    ["HUMID-PQ2 test", [new Uint8Array(0), det(200)], [new Uint8Array(0)], 64],
  ]) kdfCases.push({ label, key: key.map(hex), ctx: ctx.map(hex), out: hex(kdf(label, key, ctx, len)) });
  doc.pq2.kdf = kdfCases;
  doc.pq2.labelledHash = { label: "HUMID-PQ2 manifest", parts: [hex(utf8("a")), hex(new Uint8Array(0))], out: hex(labelledHash("HUMID-PQ2 manifest", [utf8("a"), new Uint8Array(0)])) };

  // Hybrid KEM: secret key seed (96) = d ‖ z ‖ x25519 scalar
  const seed = det(96), m = det(32), eph = det(32);
  const k = ml_kem1024.keygen(seed.subarray(0, 64));
  const xPk = x25519.getPublicKey(seed.subarray(64));
  const pkEnc = cat(header(T.KEM_PK), k.publicKey, xPk);
  const e = ml_kem1024.encapsulate(k.publicKey, m);
  const ephPk = x25519.getPublicKey(eph);
  const ssX = x25519.getSharedSecret(eph, xPk);
  const ss = kdf("HUMID-PQ2 hybrid-kem", [e.sharedSecret, ssX], [e.cipherText, ephPk, k.publicKey, xPk], 32);
  const ctEnc = cat(header(T.KEM_CT), e.cipherText, ephPk);
  doc.pq2.hybridKem = { seed: hex(seed), m: hex(m), eph: hex(eph), publicKey: hex(pkEnc), keyId: hex(keyId(pkEnc)), ciphertext: hex(ctEnc), sharedSecret: hex(ss) };

  // Sealed box to that key, with the same encapsulation randomness
  const aadParts = [utf8("acct"), utf8("doc")];
  const pt = utf8("a sealed box");
  const sk = kdf("HUMID-PQ2 sealed-box", [ss], [header(T.SEALED), cat(e.cipherText, ephPk), keyId(pkEnc)], 32);
  const body = gcmsiv(sk, new Uint8Array(12), cat(header(T.SEALED), lp(...aadParts))).encrypt(pt);
  doc.pq2.sealedBox = { type: T.SEALED, aad: aadParts.map(hex), plaintext: hex(pt), boxed: hex(cat(header(T.SEALED), e.cipherText, ephPk, body)) };

  // At-rest box
  const key = det(32), nonce = det(12);
  const parts = [utf8("item-7"), new Uint8Array([0, 0, 0, 3])];
  const pt2 = utf8("index entry");
  const ct = gcmsiv(key, nonce, cat(header(T.AT_REST), lp(...parts))).encrypt(pt2);
  doc.pq2.atRest = { type: T.AT_REST, key: hex(key), nonce: hex(nonce), aad: parts.map(hex), plaintext: hex(pt2), boxed: hex(cat(header(T.AT_REST), nonce, ct)) };
}

writeFileSync(out, JSON.stringify(doc, null, 1) + "\n");
console.log(`wrote ${out.pathname}`);
